const KIND_OF: Record<Editorial['kind'], Source['kind']> = {
  flacon: 'content',
  video: 'content',
  smm: 'content',
};

/**
 * The six evidence buckets from the brief, assembled per product so every
 * recommendation can show what it is actually standing on.
 */
export function sourcesFor(productId: string, profile: BeautyProfile): Source[] {
  const p = PRODUCTS[productId];
  const out: Source[] = [
    {
      id: `${p.id}-reviews`,
      kind: 'community',
      title: `${p.reviews.toLocaleString('ru-RU').replace(/,/g, ' ')} ${plural(p.reviews, 'отзыв', 'отзыва', 'отзывов')} покупательниц`,
      detail: p.pros.length
        ? `Чаще всего отмечают: ${p.pros.join(', ')}.${p.cons.length ? ` В минус ставят: ${p.cons.join(', ')}.` : ''}`
        : 'Отзывов пока мало, поэтому опираться на них рано.',
      meta: 'Золотое Яблоко · отзывы',
    },
    {
      id: `${p.id}-rating`,
      kind: 'community',
      title: `Рейтинг ${p.rating} из 5`,
      detail:
        p.reviews < 20
          ? 'Оценка есть, но она построена на единицах отзывов — говорю об этом честно.'
          : `Оценка устойчивая: собрана на ${p.reviews.toLocaleString('ru-RU').replace(/,/g, ' ')} отзывах.`,
      meta: 'Золотое Яблоко · рейтинг',
    },
    {
      id: `${p.id}-specs`,
      kind: 'lab',
      title: 'Характеристики продукта',
      detail: `${p.textureLabel[0].toUpperCase()}${p.textureLabel.slice(1)}. Отдушка: ${p.fragranceLabel}. Ключевое: ${p.ingredients.join(', ')}.`,
      meta: `${p.brand} · карточка состава`,
    },
  ];

  for (const cid of p.contentIds) {
    const e = EDITORIAL[cid];
    if (e) out.push({ id: e.id, kind: KIND_OF[e.kind], title: e.title, detail: e.detail, meta: e.source });
  }

  const profileLines = profileEvidence(p.id, profile);
  if (profileLines.length) {
    out.push({
      id: `${p.id}-profile`,
      kind: 'profile',
      title: 'Твой бьюти-профиль',
      detail: profileLines.join(' '),
      meta: 'Онбординг и этот диалог',
    });
  }

  if (profile.purchases.length) {
    out.push({
      id: `${p.id}-history`,
      kind: 'profile',
      title: 'История покупок',
      detail: `Ты уже покупала: ${profile.purchases.map((id) => PRODUCTS[id]?.name).filter(Boolean).join(', ')}. Я смотрю, что из этого тебе подошло.`,
      meta: 'Золотое Яблоко · заказы',
    });
  }

  return out;
}

function profileEvidence(productId: string, profile: BeautyProfile): string[] {
  const p = PRODUCTS[productId];
  const lines: string[] = [];
  if (profile.budgetMax) lines.push(`Бюджет ${formatPrice(profile.budgetMax)}: ${p.price <= profile.budgetMax ? 'проходит' : 'выше на ' + formatPrice(p.price - profile.budgetMax)}.`);
  if (profile.skinType) lines.push(`Тип кожи «${profile.skinType}».`);
  if (profile.preferences.length) lines.push(`Предпочтения: ${profile.preferences.join(', ')}.`);
  if (profile.dislikes.length) lines.push(`Не нравится: ${profile.dislikes.join(', ').toLowerCase()}.`);
  return lines;
}

export const plural = (n: number, one: string, few: string, many: string) => {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few;
  return many;
};

export const formatPrice = (value: number) => `${value.toLocaleString('ru-RU').replace(/,/g, ' ')} ₽`;
